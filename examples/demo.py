QUESTIONS = [
    "老陈是怎么走的",
    "我摔倒是哪次，怎么摔的",
    "我为什么不肯卖房子",
    "我养过狗吗",
]


def main():
    tmp = tempfile.mkdtemp(prefix="remember-me-demo-")
    try:
        st = Store(tmp)
        n = st.ingest(LIFE.splitlines())
        recs = st.load()

        s = st.stats()
        print("=" * 62)
        print(f"  建好一个库：{n} 句原话，{s['first']} → {s['last']}")
        print(f"  {os.path.getsize(st.path)} 字节"
              f"（{os.path.getsize(st.path) / max(n, 1):.0f} 字节/句）")
        print("=" * 62)

        # ---------------- 一问一答 ----------------
        for q in QUESTIONS:
            print()
            print(axis.render(recs, q, idx=st.index()))

        # ---------------- 轴 ----------------
        print()
        print("=" * 62)
        print("  人生轴：一段的长度，就是一段人生的长度")
        print("=" * 62)
        rows = axis.build_axis(recs)
        peak = max(1, max(r["anchors"] for r in rows))
        for r in rows:
            bar = "▉" * max(1, int(r["anchors"] / peak * 34))
            top = "、".join(f"{axis.KIND_CN.get(k, k)}{v}" for k, v in r["kinds"])
            print(f"  {r['year']}  {r['n']:>3}句  {r['anchors']:>3}刻度  {top:<20} {bar}")

        print()
        print("  刻度跨度（这才是『一段』）：")
        for m in axis.milestones(recs)[:6]:
            yrs = m["span_days"] / axis.DAYS_PER_YEAR
            print(f"    {m['cn']:<6} {m['n']:>3}次  跨 {yrs:>4.1f} 年   "
                  f"{m['first']['d']} → {m['last']['d']}")

        print()
        sp = axis.spine(recs)          # 建一次就够，别在 print 和循环里各调一遍
        print("  ★ 常驻刻度层：一生中最重的", len(sp), "句，永远在上下文里")
        for r in sp[:5]:
            print(f"    {r['d']}  {r['text'][:40]}")
        print()
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


if __name__ == "__main__":
    main()
